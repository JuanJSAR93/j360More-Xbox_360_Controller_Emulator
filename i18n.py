def get_text(lang: str, key: str, **kwargs) -> str:
    lang = lang if lang in STRINGS else "es"
    val = STRINGS[lang].get(key, STRINGS["es"].get(key, key))
    if kwargs and isinstance(val, str):
        return val.format(**kwargs)
    return val

def get_target_name(lang: str, target: str, emulated_type: str = "xbox360") -> str:
    lang = lang if lang in STRINGS else "es"
    if emulated_type in ("ds4", "dualsense"):
        targets_ds4 = STRINGS[lang].get("target_names_ds4", {})
        if target in targets_ds4:
            return targets_ds4[target]
        if target in STRINGS["es"].get("target_names_ds4", {}):
            return STRINGS["es"]["target_names_ds4"][target]
    elif emulated_type == "ns2pro":
        targets_ns2 = STRINGS[lang].get("target_names_ns2pro", {})
        if target in targets_ns2:
            return targets_ns2[target]
        if target in STRINGS["es"].get("target_names_ns2pro", {}):
            return STRINGS["es"]["target_names_ns2pro"][target]
    targets = STRINGS[lang].get("target_names", {})
    return targets.get(target, STRINGS["es"]["target_names"].get(target, target))

